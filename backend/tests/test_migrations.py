"""T010 -- the migration path works from clean.

Alembic is run as a subprocess, the same way a person runs it, rather than through its
Python API. The API path would let the test pass while `alembic upgrade head` on the
command line still failed on a bad alembic.ini or an import that only resolves because
pytest already put `backend/` on the path -- which is precisely the failure this test
exists to catch.
"""

from __future__ import annotations

import os
import sqlite3
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path

import pytest
from sqlalchemy import text

from app.db import Base, get_engine, get_sessionmaker
from app.settings import get_settings

BACKEND = Path(__file__).parent.parent.resolve()


@pytest.fixture
def temp_database(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[None]:
    """Point the cached engine at a throwaway file, and put it back afterwards.

    Settings and engine are both `lru_cache`d -- once per process is the right lifetime
    in production and the wrong one in a test, so the caches are cleared on both sides.
    """
    monkeypatch.setenv("LEKGOTLA_DATABASE_URL", f"sqlite:///{tmp_path / 'session.db'}")
    get_settings.cache_clear()
    get_engine.cache_clear()
    get_sessionmaker.cache_clear()
    yield
    monkeypatch.undo()
    get_settings.cache_clear()
    get_engine.cache_clear()
    get_sessionmaker.cache_clear()


def _alembic(*args: str, database_url: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-m", "alembic", *args],
        cwd=BACKEND,
        env={**os.environ, "LEKGOTLA_DATABASE_URL": database_url},
        capture_output=True,
        text=True,
        timeout=120,
    )


@pytest.fixture
def database_url(tmp_path: Path) -> str:
    return f"sqlite:///{tmp_path / 'test.db'}"


def test_upgrade_head_runs_from_clean(database_url: str, tmp_path: Path) -> None:
    result = _alembic("upgrade", "head", database_url=database_url)

    assert result.returncode == 0, result.stderr
    tables = {
        row[0]
        for row in sqlite3.connect(tmp_path / "test.db").execute("select name from sqlite_master where type='table'")
    }
    assert "alembic_version" in tables


def test_downgrade_returns_to_base(database_url: str) -> None:
    assert _alembic("upgrade", "head", database_url=database_url).returncode == 0

    result = _alembic("downgrade", "base", database_url=database_url)

    assert result.returncode == 0, result.stderr
    assert _alembic("current", database_url=database_url).stdout.strip() == ""


def test_the_schema_and_the_migrations_do_not_disagree(database_url: str) -> None:
    # An autogenerated revision against an up-to-date database should be empty. When it
    # is not, someone added a model without a migration -- the failure that turns
    # "it works on my machine" into a production outage.
    assert _alembic("upgrade", "head", database_url=database_url).returncode == 0

    result = _alembic("check", database_url=database_url)

    assert result.returncode == 0, f"models and migrations have drifted:\n{result.stdout}{result.stderr}"


@pytest.mark.usefixtures("temp_database")
def test_the_session_factory_produces_a_usable_session() -> None:
    with get_sessionmaker()() as session:
        assert session.execute(text("select 1")).scalar_one() == 1


@pytest.mark.usefixtures("temp_database")
def test_sqlite_enforces_foreign_keys() -> None:
    # Off by default in SQLite, per connection. app/db/session.py turns it on; without
    # that, a reference to a deleted row fails silently instead of raising.
    with get_sessionmaker()() as session:
        assert session.execute(text("PRAGMA foreign_keys")).scalar_one() == 1


def test_the_naming_convention_is_attached_to_the_metadata() -> None:
    # The convention is what makes a later ALTER possible on SQLite: an unnamed
    # constraint cannot be dropped. Assert it is actually attached, so it cannot be
    # dropped from Base without a test noticing.
    assert set(Base.metadata.naming_convention) >= {"ix", "uq", "ck", "fk", "pk"}
